import { useState, useMemo, useEffect } from "react"
import { Link, useSearchParams } from "react-router"
import { SearchInput } from "@/components/search-input"
import { useDatasets } from "./api/use-datasets"
import { DatasetTable } from "./components/dataset-table"
import { DatasetDetailPanel } from "./components/dataset-detail-panel"
import { ErrorState } from "@/components/error-state"
import { PageHeader } from "@/components/page-header"
import { TableSkeleton } from "@/components/table-skeleton"
import { Button } from "@/components/ui/button"
import {
  Empty,
  EmptyHeader,
  EmptyMedia,
  EmptyTitle,
  EmptyDescription,
  EmptyContent,
} from "@/components/ui/empty"
import { Database, ArrowRight, Sparkles, GraduationCap, Search } from "lucide-react"
import type { DatasetRecord } from "@/types/api"

export default function DatasetsPage() {
  const { data: datasets = [], isLoading, isError, error, refetch } = useDatasets()
  const [page, setPage] = useState(0)
  const [search, setSearch] = useState("")
  const [selectedDataset, setSelectedDataset] = useState<DatasetRecord | null>(null)
  const [detailOpen, setDetailOpen] = useState(false)
  const [searchParams, setSearchParams] = useSearchParams()

  useEffect(() => {
    const runId = searchParams.get("run")
    const jobId = searchParams.get("job")
    if (datasets.length > 0 && (runId || jobId)) {
      const ds = runId
        ? datasets.find((d) => d.run_id === runId)
        : datasets.find((d) => d.tags?.job_id === jobId)
      if (ds) {
        // eslint-disable-next-line react-hooks/set-state-in-effect -- one-time URL param sync
        setSelectedDataset(ds)
        setDetailOpen(true)
        setSearchParams({}, { replace: true })
      }
    }
  }, [searchParams, datasets, setSearchParams])

  const filteredDatasets = useMemo(() => {
    if (!search.trim()) return datasets
    const q = search.toLowerCase()
    return datasets.filter((d) => d.name.toLowerCase().includes(q))
  }, [datasets, search])

  function handleSelectDataset(ds: DatasetRecord) {
    setSelectedDataset(ds)
    setDetailOpen(true)
  }

  if (isError) {
    return <ErrorState message={error?.message} onRetry={() => void refetch()} />
  }

  return (
    <div className="space-y-6">
      <div data-tutorial="datasets-header" className="space-y-4">
        <PageHeader title="Datasets" description="Browse and inspect your generated training data" />

        <div className="animate-message-in rounded-xl border bg-card p-4">
        <div className="grid gap-3 md:grid-cols-3 mb-3">
          <div className="flex items-start gap-2.5">
            <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-md bg-[#ece6ff] text-[#5e40be] dark:bg-[#1b0d33]/40 dark:text-[#876fd4]">
              <Sparkles className="h-3.5 w-3.5" />
            </div>
            <div>
              <p className="text-sm font-medium">Synthetic Data</p>
              <p className="text-xs text-muted-foreground">Generated by SDG recipes using a teacher model</p>
            </div>
          </div>
          <div className="flex items-start gap-2.5">
            <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-md bg-[#e0f0ff] text-[#0066cc] dark:bg-[#003366]/40 dark:text-[#4394e5]">
              <GraduationCap className="h-3.5 w-3.5" />
            </div>
            <div>
              <p className="text-sm font-medium">Training-Ready</p>
              <p className="text-xs text-muted-foreground">Use as input when fine-tuning models</p>
            </div>
          </div>
          <div className="flex items-start gap-2.5">
            <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-md bg-[#fff4cc] text-[#b98412] dark:bg-[#54330b]/40 dark:text-[#dca614]">
              <Search className="h-3.5 w-3.5" />
            </div>
            <div>
              <p className="text-sm font-medium">Inspectable</p>
              <p className="text-xs text-muted-foreground">Click any dataset to browse actual training samples</p>
            </div>
          </div>
        </div>
        <p className="text-xs text-muted-foreground border-t pt-3">
          Stored in MLflow. Generate your first dataset from{" "}
          <Link to="/chat" className="inline-flex items-center gap-0.5 underline underline-offset-2 hover:text-foreground transition-colors">
            Chat <ArrowRight className="h-2.5 w-2.5" />
          </Link>{" "}
          or an{" "}
          <Link to="/recipes" className="underline underline-offset-2 hover:text-foreground transition-colors">
            SDG recipe
          </Link>.
        </p>
      </div>
      </div>

      <SearchInput value={search} onChange={(v) => { setSearch(v); setPage(0) }} placeholder="Search datasets..." />

      {isLoading ? (
        <TableSkeleton columns={4} />
      ) : filteredDatasets.length > 0 ? (
        <DatasetTable
          datasets={filteredDatasets}
          page={page}
          onPageChange={setPage}
          onSelectDataset={handleSelectDataset}
        />
      ) : (
        <Empty className="border mt-4">
          <EmptyHeader>
            <EmptyMedia variant="icon"><Database /></EmptyMedia>
            <EmptyTitle>No datasets yet</EmptyTitle>
            <EmptyDescription>Datasets are created by running SDG recipes.</EmptyDescription>
          </EmptyHeader>
          <EmptyContent>
            <Button asChild><Link to="/recipes">Browse Recipes</Link></Button>
          </EmptyContent>
        </Empty>
      )}

      <DatasetDetailPanel
        dataset={selectedDataset}
        open={detailOpen}
        onOpenChange={setDetailOpen}
      />
    </div>
  )
}
